def _products() -> list[Product]:
    out: list[Product] = []
    for kind in KINDS:
        for i, (brand, line, price, suits) in enumerate(kind.stock):
            out.append(
                Product(
                    f"{kind.key}-{i}",
                    f"{kind.name} {brand} {line}",
                    brand,
                    kind.category,
                    price,
                    f"{kind.about}، {suits}",
                )
            )
    return out


