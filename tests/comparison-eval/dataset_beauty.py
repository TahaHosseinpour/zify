def of_kind(kind: str) -> list[Product]:
    """The ten products of one kind, in the order they are listed above."""
    return [p for p in PRODUCTS if p.key.rsplit("-", 1)[0] == kind]


def line_of(product: Product) -> str:
    """The words that identify a product inside a reply: its line name."""
    kind = KIND[product.key.rsplit("-", 1)[0]]
    return kind.stock[int(product.key.rsplit("-", 1)[1])][1]


def product(kind: str, brand: str, line: str | None = None) -> Product:
    """The product of `kind` by `brand` (and, where the brand has two, `line`)."""
    found = [p for p in of_kind(kind) if p.brand == brand and (line is None or line_of(p) == line)]
    assert len(found) == 1, (kind, brand, line, found)
    return found[0]


def _check() -> None:
    assert len(KINDS) == 30 and all(len(k.stock) == 10 for k in KINDS)
    assert len(PRODUCTS) == 300 and len(BY_KEY) == 300
    for k in KINDS:
        prices = [s[2] for s in k.stock]
        assert len(set(prices)) == 10, f"{k.key}: two products with one price"
        lines = [s[1] for s in k.stock]
        brands_lines = [(s[0], s[1]) for s in k.stock]
        assert len(set(brands_lines)) == 10, f"{k.key}: a product listed twice"
        assert len(set(lines)) == 10, f"{k.key}: two products with one line name"


_check()


