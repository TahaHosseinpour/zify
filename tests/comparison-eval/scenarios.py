def _check_nike(o: Outcome) -> None:
    assert _says(o, "ایرزوم", "پگاسوس", "زوم فلای"), "هیچ‌کدام از سه کفش نایک فروشگاه نام برده نشد"
    assert not _says(o, "نداریم", "موجود نیست"), "وجود کفش نایک انکار شد"


_OVER_20M = ["ثینک پد", "پروبوک", "لتیتود", "زنبوک", "اچ پی امن", "tuf", "لیجن"]


def _check_laptop_budget(o: Outcome) -> None:
    assert _says(o, "expertbook", "ویووبوک", "آیدیاپد"), "هیچ لپ‌تاپ زیر ۲۰ میلیونی نام برده نشد"
    offered = [name for name in _OVER_20M if _says(o, name)]
    assert not offered, f"لپ‌تاپ بالای ۲۰ میلیون پیشنهاد شد: {offered}"


def _check_cheapest_runner(o: Outcome) -> None:
    assert _says(o, "ولوسیتی"), "ارزان‌ترین کفش دویدن (پوما ولوسیتی، ۱٬۲۵۰٬۰۰۰) نام برده نشد"
    others = [p.name for p in PRODUCTS if p.category == "کفش ورزشی" and p.key != "shoe-run-5"]
    first = min((fold(o.reply).find(fold(n)) for n in others if _says(o, n)), default=-1)
    assert first < 0 or fold(o.reply).find("ولوسیتی") < first, "کفش دیگری پیش از ارزان‌ترین معرفی شد"


def _check_motorcycle(o: Outcome) -> None:
    assert _says(o, "نداریم", "موجود نیست", "ندارم", "نیست"), "نبود موتورسیکلت صریح گفته نشد"
    assert not _says(o, "تومان"), "برای کالایی که نداریم قیمت آورده شد"
    assert not o.cards, f"برای کالایی که نداریم کارت محصول نمایش داده شد: {[c['name'] for c in o.cards]}"


def _check_shipping(o: Outcome) -> None:
    assert _says(o, "پیشتاز"), "روش ارسال (پست پیشتاز) گفته نشد"
    assert _says(o, "2 تا 4", "2 الی 4", "دو تا چهار"), "مدت ارسال (۲ تا ۴ روز کاری) گفته نشد"


