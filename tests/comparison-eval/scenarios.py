"""The comparison scenarios: twenty whole conversations, plus three about how
many products a reply is followed by.

S01-S20 are the scenarios of EVALUATION_FA.md, with the same customer messages
and the same acceptance criteria. Each is one or more customer messages; the
agent carries the whole conversation itself and only its last reply is scored.
Five are checked in code (`check`), fifteen by the jury (`rubric` + `ideal`).

R01-R03 are new and not part of that twenty: they check the product *cards*
that accompany a reply, which the original scenarios never looked at.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Callable, Optional

from dataset import BY_KEY, PRODUCTS, fa_number


@dataclass
class Outcome:
    """What the customer got from the last turn: the text, and what came with it."""

    reply: str
    cards: list[dict]  # {"id", "name", "price", "productUrl"} - product cards under the reply
    purchase_url: Optional[str]
    show_buy_actions: bool


@dataclass
class Scenario:
    id: str
    title: str
    group: str
    messages: list[str]
    check: Optional[Callable[[Outcome], None]] = None  # raises AssertionError
    rubric: str = ""
    ideal: str = ""

    @property
    def kind(self) -> str:
        return "قطعی" if self.check else "داوری‌شده"


_FOLD = str.maketrans(
    {"‌": " ", "ي": "ی", "ك": "ک", **{fa: str(d) for d, fa in enumerate("۰۱۲۳۴۵۶۷۸۹")}}
)


def fold(text: str) -> str:
    """Lower-cased, half-spaces opened, Persian digits latinised - so a check
    doesn't fail on how a word happened to be typed."""
    return " ".join(text.lower().translate(_FOLD).split())


def _says(outcome: Outcome, *needles: str) -> bool:
    text = fold(outcome.reply)
    return any(fold(n) in text for n in needles)


NO_INVENTION = (
    "هیچ محصول، قیمت، مشخصه، لینک، سیاست یا وعده‌ای خارج از داده‌های فروشگاه نسازد؛ ساختن هر یک "
    "به‌تنهایی موجب رد است."
)

# ── S01-S05: checked in code ─────────────────────────────────────────────────


def _check_nike(o: Outcome) -> None:
    assert _says(o, "ایرزوم", "پگاسوس", "زوم فلای"), "هیچ‌کدام از سه کفش نایک فروشگاه نام برده نشد"
    assert not _says(o, "نداریم", "موجود نیست"), "وجود کفش نایک انکار شد"


_OVER_20M = ["ثینک پد", "پروبوک", "لتیتود", "زنبوک", "امن", "tuf", "لیجن"]


def _check_laptop_budget(o: Outcome) -> None:
    assert _says(o, "expertbook", "ویووبوک", "آیدیاپد"), "هیچ لپ‌تاپ زیر ۲۰ میلیونی نام برده نشد"
    offered = [name for name in _OVER_20M if _says(o, name)]
    assert not offered, f"لپ‌تاپ بالای ۲۰ میلیون پیشنهاد شد: {offered}"


def _check_cheapest_runner(o: Outcome) -> None:
    assert _says(o, "ولوسیتی"), "ارزان‌ترین کفش دویدن (پوما ولوسیتی، ۱٬۲۵۰٬۰۰۰) نام برده نشد"
    others = [p.name for p in PRODUCTS if p.category == "کفش ورزشی" and p.key != "shoe-run-5"]
    first = min((fold(o.reply).find(fold(n)) for n in others if _says(o, n)), default=-1)
    assert first < 0 or fold(o.reply).find("ولوسیتی") < first, "کفش دیگری پیش از ارزان‌ترین معرفی شد"


def _check_motorcycle(o: Outcome) -> None:
    assert _says(o, "نداریم", "موجود نیست", "ندارم", "نیست"), "نبود موتورسیکلت صریح گفته نشد"
    assert not _says(o, "تومان"), "برای کالایی که نداریم قیمت آورده شد"
    assert not o.cards, f"برای کالایی که نداریم کارت محصول نمایش داده شد: {[c['name'] for c in o.cards]}"


def _check_shipping(o: Outcome) -> None:
    assert _says(o, "پیشتاز"), "روش ارسال (پست پیشتاز) گفته نشد"
    assert _says(o, "2 تا 4", "2 الی 4", "دو تا چهار"), "مدت ارسال (۲ تا ۴ روز کاری) گفته نشد"


# ── R01-R03: the cards under the reply ───────────────────────────────────────


def _cards_are(expected_keys: set[str], what: str) -> Callable[[Outcome], None]:
    expected_ids = {BY_KEY[k].id for k in expected_keys}

    def check(o: Outcome) -> None:
        shown = {c["id"] for c in o.cards}
        assert shown, "هیچ کارت محصولی نمایش داده نشد"
        extra = [c["name"] for c in o.cards if c["id"] not in expected_ids]
        assert not extra, f"کارت نامرتبط نمایش داده شد ({what}): {extra}"

    return check


